#!/usr/bin/env bun
// Regenerates public/vendor/playground-data.js — the seed data (site logo +
// starter files) for public/playground.html. public/ is deployed standalone,
// so the playground can't fetch docs/*.md at runtime (see the same note next
// to renderDemo() in index.html); this bakes them in instead.
//
// Run after editing docs/example-*.md, playground/demo.md, or the logo in
// index.html:
//   bun scripts/gen-playground-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const idx = readFileSync(join(ROOT, "public/index.html"), "utf8");
const m = idx.match(/data:image\/webp;base64,[A-Za-z0-9+/=]+/);
if (!m) throw new Error("logo data URI not found in public/index.html");
const LOGO = m[0];

const demo = readFileSync(join(ROOT, "public/playground/demo.md"), "utf8");

const exampleNames = [
  "example-invoice.md",
  "example-invoice-drift.md",
  "example-quote-plain.md",
  "example-charts.md",
  "example-executable-documentation.md",
];

const files = { "demo.md": demo };
for (const name of exampleNames) {
  files[name] = readFileSync(join(ROOT, "docs", name), "utf8");
}

const out = `// Generated by scripts/gen-playground-data.mjs — do not hand-edit.
// Seed data for public/playground.html: the site logo and the starter files
// shown in the FILES panel (public/ is deployed standalone, so these can't be
// fetched from ../docs at runtime — see the same note in index.html).
//
// Loaded as a classic <script>, not a module — playground.html is meant to be
// opened straight from disk (file://), which blocks ES module imports via
// CORS — so this assigns plain globals instead of using \`export\`.
window.LOGO_DATA_URI = ${JSON.stringify(LOGO)};

window.FILES = ${JSON.stringify(files, null, 2)};
`;

const outPath = join(ROOT, "public/vendor/playground-data.js");
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${out.length} bytes)`);
