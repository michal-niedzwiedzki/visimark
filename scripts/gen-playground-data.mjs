#!/usr/bin/env bun
// Regenerates docs/vendor/playground-data.js — the one thing docs/playground.html
// still can't fetch itself: the site logo, embedded in docs/index.html as a
// base64 data URI rather than a standalone image file. Everything else the
// playground needs (demo.md, the example-*.md files) now lives alongside it
// in docs/ and is fetched at runtime — see FILE_SOURCES in playground.html.
//
// Run after changing the logo in docs/index.html:
//   bun scripts/gen-playground-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const idx = readFileSync(join(ROOT, "docs/index.html"), "utf8");
const m = idx.match(/data:image\/webp;base64,[A-Za-z0-9+/=]+/);
if (!m) throw new Error("logo data URI not found in docs/index.html");
const LOGO = m[0];

const out = `// Generated by scripts/gen-playground-data.mjs — do not hand-edit.
// Seed data for docs/playground.html: the site logo, embedded in
// docs/index.html as a data URI rather than a standalone image file (see
// the same note in gen-playground-data.mjs).
//
// Loaded as a classic <script>, not a module, so it can assign a plain
// global instead of \`export\`ing.
window.LOGO_DATA_URI = ${JSON.stringify(LOGO)};
`;

const outPath = join(ROOT, "docs/vendor/playground-data.js");
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${out.length} bytes)`);
