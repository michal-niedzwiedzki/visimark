import { describe, expect, test } from "bun:test";
import { looksGenerated, selectFiles } from "../src/policy.js";

const files = (...paths: string[]) => paths.map((path) => ({ path, size: 100 }));

describe("selectFiles", () => {
  test("drops dot-paths at any depth, keeps a dotted segment", () => {
    const r = selectFiles(
      files(
        ".github/ISSUE_TEMPLATE/bug.md",
        "docs/.internal/notes.md",
        ".env.md",
        "docs/v1.2/notes.md",
      ),
    );
    expect(r.markdown).toEqual(["docs/v1.2/notes.md"]);
    expect(r.skipped).toEqual([
      { path: ".github/ISSUE_TEMPLATE/bug.md", reason: "dot-path" },
      { path: "docs/.internal/notes.md", reason: "dot-path" },
      { path: ".env.md", reason: "dot-path" },
    ]);
  });

  test("excluded-directory is case-insensitive per segment", () => {
    const r = selectFiles(
      files("docs/Tests/a.md", "docs/testing/a.md", "vendor/x.md", "a/__tests__/b.md"),
    );
    expect(r.markdown).toEqual(["docs/testing/a.md"]);
    expect(r.skipped.map((s) => s.reason)).toEqual([
      "excluded-directory",
      "excluded-directory",
      "excluded-directory",
    ]);
  });

  test("size cap is > 500000", () => {
    const r = selectFiles([
      { path: "a.md", size: 500_000 },
      { path: "b.md", size: 500_001 },
    ]);
    expect(r.markdown).toEqual(["a.md"]);
    expect(r.skipped).toEqual([{ path: "b.md", reason: "size" }]);
  });

  test("first matching reason wins", () => {
    expect(selectFiles(files(".github/test/a.md")).skipped).toEqual([
      { path: ".github/test/a.md", reason: "dot-path" },
    ]);
  });

  test("file cap keeps the first N in byte order and records file-cap", () => {
    const r = selectFiles(files("c.md", "a.md", "B.md", "b.md"), 2);
    expect(r.markdown).toEqual(["B.md", "a.md"]);
    expect(r.skipped).toEqual([
      { path: "b.md", reason: "file-cap" },
      { path: "c.md", reason: "file-cap" },
    ]);
  });

  test("non-Markdown paths are neither kept nor skipped", () => {
    expect(selectFiles(files("a.txt", "x.csv", "README.MD", "n.markdown"))).toEqual({
      markdown: ["README.MD", "n.markdown"],
      skipped: [],
    });
  });
});

describe("looksGenerated", () => {
  test("a DO NOT EDIT header", () => {
    expect(looksGenerated("<!-- DO NOT EDIT: generated by gen.ts -->\n# x\n")).toBe(true);
  });

  test("an ordinary document", () => {
    expect(looksGenerated("# Budget\n\nGenerated revenue grew.\n")).toBe(false);
  });

  test("only the first 15 lines count", () => {
    expect(looksGenerated(`${"x\n".repeat(15)}@generated\n`)).toBe(false);
  });
});
